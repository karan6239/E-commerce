// Helper Functions
function getAllProducts() {
    return NOVA_PRODUCTS;
}

function getProductsByCategory(category) {
    if (!category || category === 'all') return NOVA_PRODUCTS;
    const cat = category.toLowerCase().trim();
    if (cat === 'winter' || cat === 'winterc') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'winterc' || p.category.toLowerCase() === 'winter'));
    }
    if (cat === 'linen' || cat === 'lenin') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'linen' || p.category.toLowerCase() === 'lenin'));
    }
    if (cat === 'streetwear' || cat === 'street' || cat === 'street wear' || cat === 'street wears') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'streetwear' || p.category.toLowerCase() === 'street'));
    }
    if (cat === 'utility' || cat === 'utility jacket' || cat === 'utility jackets') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'utility' || p.category.toLowerCase() === 'utility jackets'));
    }
    if (cat === 'oldmoney' || cat === 'old money' || cat === 'old_money' || cat === 'money') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'oldmoney' || p.category.toLowerCase() === 'old money'));
    }
    if (cat === 'office' || cat === 'office wear' || cat === 'office wears') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'office' || p.category.toLowerCase() === 'office wear'));
    }
    if (cat === 'party' || cat === 'party wear' || cat === 'party wears') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'party' || p.category.toLowerCase() === 'party wear'));
    }
    if (cat === 'gym' || cat === 'gym wear' || cat === 'gym wears') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'gym' || p.category.toLowerCase() === 'gym wear'));
    }
    if (cat === 'beach' || cat === 'beach wear' || cat === 'beach wears') {
        return NOVA_PRODUCTS.filter(p => p.category && (p.category.toLowerCase() === 'beach' || p.category.toLowerCase() === 'beach wear'));
    }
    return NOVA_PRODUCTS.filter(p => p.category && p.category.toLowerCase() === cat);
}

function getProductById(id) {
    if (!id) return null;
    const idStr = String(id).toLowerCase();
    return NOVA_PRODUCTS.find(p => String(p.id).toLowerCase() === idStr || String(p.id) === idStr) || null;
}

function searchProducts(query) {
    if (!query) return NOVA_PRODUCTS;
    const q = query.toLowerCase().trim();
    return NOVA_PRODUCTS.filter(p => 
        (p.name && p.name.toLowerCase().includes(q)) ||
        (p.category && p.category.toLowerCase().includes(q)) ||
        (p.subCategory && p.subCategory.toLowerCase().includes(q)) ||
        (p.description && p.description.toLowerCase().includes(q)) ||
        (p.badge && p.badge.toLowerCase().includes(q))
    );
}

// Expose globally to window
if (typeof window !== 'undefined') {
    window.NOVA_PRODUCTS = NOVA_PRODUCTS;
    window.getAllProducts = getAllProducts;
    window.getProductsByCategory = getProductsByCategory;
    window.getProductById = getProductById;
    window.searchProducts = searchProducts;
}
